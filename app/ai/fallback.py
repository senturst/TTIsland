_rng = random.SystemRandom()


def pick(content_type: str) -> str:
    pool = TEMPLATES.get(content_type)
    if not pool:
        return ""
    return _rng.choice(pool)


def pick_deterministic(content_type: str, seed_key: str) -> str:
    """同一次运行内对同一目标返回稳定的兜底文本，避免刷新后文字跳变。"""
    pool = TEMPLATES.get(content_type)
    if not pool:
        return ""
    return pool[hash(seed_key) % len(pool)]
